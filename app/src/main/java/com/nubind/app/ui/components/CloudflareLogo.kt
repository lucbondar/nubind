/** Logo de Cloudflare con sus cuatro tonos (se lee bien sobre fondo claro y oscuro). */
internal fun buildCloudflareLogo(name: String): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 256f,
        viewportHeight = 256f
    )
        .addPath(addPathNodes(CloudflareLogoPaths.MAIN), pathFillType = PathFillType.EvenOdd, fill = SolidColor(CfMain))
        .addPath(addPathNodes(CloudflareLogoPaths.DARK), pathFillType = PathFillType.EvenOdd, fill = SolidColor(CfDark))
        .addPath(addPathNodes(CloudflareLogoPaths.TAN), pathFillType = PathFillType.EvenOdd, fill = SolidColor(CfTan))
        .addPath(addPathNodes(CloudflareLogoPaths.LIGHT), pathFillType = PathFillType.EvenOdd, fill = SolidColor(CfLight))
        .build()
